export async function GET(_req: Request, { params }: { params: Promise<{ id: string }> }) {
  try {
    const { id: vehicleId } = await params;
    const supabase = createClient();
    const {
      data: { user },
    } = await supabase.auth.getUser();
    if (!user) return NextResponse.json({ error: 'Unauthenticated' }, { status: 401 });

    const [vehicle, profile] = await Promise.all([getVehicle(vehicleId), getProfile()]);
    if (!vehicle) return NextResponse.json({ error: 'Vehicle not found' }, { status: 404 });
    if (vehicle.userId !== user.id) return NextResponse.json({ error: 'Forbidden' }, { status: 403 });

    const entitlement = await canExportCertificate(profile, vehicleId);
    if (!entitlement.allowed) {
      return NextResponse.json({ error: 'Certified dossier requires Pro or a one-off purchase', code: 'payment_required' }, { status: 402 });
    }

    const lang: 'en' | 'fr' = profile?.locale === 'fr' ? 'fr' : 'en';
    const c = COPY[lang];
    const intl = lang === 'fr' ? 'fr-FR' : 'en-GB';
    const fmtDate = (iso: string | null | undefined) => (iso ? new Date(iso).toLocaleDateString(intl, { day: '2-digit', month: 'short', year: 'numeric' }) : '—');
    const fmtMoney = (n: number, cur: string) => {
      try {
        return new Intl.NumberFormat(intl, { style: 'currency', currency: cur, maximumFractionDigits: 0 }).format(n);
      } catch {
        return `${n} ${cur}`;
      }
    };

    const [{ data: rows }, known] = await Promise.all([
      supabase
        .from('maintenance_entries')
        .select('id, vehicle_id, occurred_at, category, description, cost, currency, garage_name, mileage_km, previous_hash, hash, created_at')
        .eq('vehicle_id', vehicleId)
        .order('created_at', { ascending: true }),
      getKnownIssues(vehicle, profile?.country),
    ]);
    const chainRows = (rows ?? []) as unknown as (ChainRow & { created_at: string })[];
    const verdict = verifyChain(chainRows);

    // ── PDF ────────────────────────────────────────────────────────
    const pdf = await PDFDocument.create();
    pdf.setTitle(`${c.title} — ${vehicle.make} ${vehicle.model} ${vehicle.plate}`);
    pdf.setAuthor('Keeper');
    pdf.setCreator('Keeper');
    const font = await pdf.embedFont(StandardFonts.Helvetica);
    const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
    const mono = await pdf.embedFont(StandardFonts.Courier);

    const A4: [number, number] = [595.28, 841.89];
    const margin = 46;
    let page = pdf.addPage(A4);
    let y = A4[1] - margin;
    const dossierId = `VW-${crypto.createHash('sha256').update(`${vehicleId}:${chainRows.at(-1)?.hash ?? 'genesis'}`).digest('hex').slice(0, 10).toUpperCase()}`;

    const header = (p: PDFPage) => {
      p.drawRectangle({ x: 0, y: A4[1] - 96, width: A4[0], height: 96, color: INK });
      p.drawText('KEEPER', { x: margin, y: A4[1] - 44, size: 18, font: bold, color: rgb(1, 1, 1) });
      p.drawText(c.title, { x: margin, y: A4[1] - 66, size: 11, font, color: rgb(0.8, 0.8, 0.82) });
      p.drawText(`${c.reportId}: ${dossierId}`, { x: A4[0] - margin - 190, y: A4[1] - 44, size: 9, font: mono, color: rgb(0.8, 0.8, 0.82) });
    };
    const footer = (p: PDFPage) => {
      const txt = safe(c.generated(new Date().toLocaleDateString(intl, { day: '2-digit', month: 'long', year: 'numeric' })));
      p.drawText(wrap(txt, font, 8, A4[0] - margin * 2)[0] ?? txt, { x: margin, y: 40, size: 8, font, color: MUTED });
      p.drawText(c.verify, { x: margin, y: 28, size: 8, font: mono, color: MUTED });
    };
    const newPage = () => {
      footer(page);
      page = pdf.addPage(A4);
      header(page);
      y = A4[1] - 120;
    };
    const ensure = (h: number) => {
      if (y - h < 70) newPage();
    };
    const text = (raw: string, size = 10, f: PDFFont = font, color = INK, x = margin) => {
      const s = safe(raw);
      ensure(size + 6);
      page.drawText(s, { x, y, size, font: f, color });
      y -= size + 6;
    };

    header(page);
    y = A4[1] - 124;

    // Vehicle block
    text(c.vehicle, 14, bold);
    y -= 2;
    text(`${vehicle.make} ${vehicle.model}${vehicle.trim ? ` ${vehicle.trim}` : ''} · ${vehicle.year}`, 11, bold);
    text(`${c.plate}: ${vehicle.plate}    ${vehicle.vin ? `${c.vin}: ${vehicle.vin}` : ''}`, 10, mono, MUTED);
    text(`${c.odometer}: ${vehicle.currentMileageKm.toLocaleString(intl)} km    ${c.fuel}: ${vehicle.fuelType}`, 10, font, MUTED);
    y -= 8;

    // Integrity block
    page.drawRectangle({ x: margin, y: y - 34, width: A4[0] - margin * 2, height: 42, color: verdict.linked ? rgb(0.93, 0.98, 0.95) : rgb(1, 0.96, 0.9), borderColor: verdict.linked ? OK : WARN, borderWidth: 1 });
    page.drawText(verdict.linked ? c.chainOk : c.chainBroken, { x: margin + 10, y: y - 10, size: 9, font: bold, color: verdict.linked ? OK : WARN });
    page.drawText(c.content(verdict.contentVerified, verdict.entries), { x: margin + 10, y: y - 25, size: 8.5, font, color: MUTED });
    y -= 56;

    // Official records
    if (known.mot || (known.nhtsa && known.nhtsa.recalls.length)) {
      if (known.mot) {
        text(c.mot, 12, bold);
        text(c.motLine(known.mot.tests.length, Math.round(known.mot.failRate * 100), fmtDate(known.mot.motExpiryDate)), 10, font, MUTED);
        const odo = known.mot.tests.filter((t) => t.odometerValue != null).slice(0, 8);
        if (odo.length) {
          text(c.motOdo, 9, bold, MUTED);
          const line = safe(odo.map((t) => `${t.completedDate.slice(0, 7)} ${t.odometerValue?.toLocaleString(intl)} ${t.odometerUnit === 'MI' ? 'mi' : 'km'}`).join('   '));
          for (const l of wrap(line, mono, 8, A4[0] - margin * 2)) text(l, 8, mono, MUTED);
        }
        y -= 4;
      }
      if (known.nhtsa?.recalls.length) {
        text(c.recalls(known.nhtsa.recalls.length), 10, bold, WARN);
        for (const r of known.nhtsa.recalls.slice(0, 4)) {
          for (const l of wrap(safe(`• ${r.component}: ${r.summary}`), font, 8.5, A4[0] - margin * 2 - 10)) text(l, 8.5, font, MUTED, margin + 6);
        }
        y -= 4;
      }
    }

    // Service history table
    text(c.history, 14, bold);
    y -= 2;
    const cols = [0, 62, 118, 300, 400, 460];
    const drawRow = (cells: string[], f: PDFFont, size: number, color = INK) => {
      ensure(size + 8);
      cells.forEach((cell, i) => {
        const maxW = (cols[i + 1] ?? A4[0] - margin * 2) - cols[i] - 6;
        page.drawText(clip(safe(cell), f, size, maxW), { x: margin + cols[i], y, size, font: f, color });
      });
      y -= size + 8;
    };
    drawRow(c.columns, bold, 8, MUTED);
    page.drawLine({ start: { x: margin, y: y + 4 }, end: { x: A4[0] - margin, y: y + 4 }, thickness: 0.5, color: rgb(0.85, 0.85, 0.87) });
    if (chainRows.length === 0) text(c.empty, 10, font, MUTED);
    for (const r of [...chainRows].reverse()) {
      drawRow(
        [fmtDate(r.occurred_at), `${Number(r.mileage_km).toLocaleString(intl)}`, r.description, r.garage_name, fmtMoney(Number(r.cost), r.currency), r.hash.slice(0, 12)],
        font,
        8.5,
      );
    }

    footer(page);
    const bytes = await pdf.save();
    return new Response(Buffer.from(bytes), {
      status: 200,
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `inline; filename="keeper-dossier-${vehicle.plate.replace(/\s+/g, '')}.pdf"`,
        'Cache-Control': 'private, no-store',
      },
    });
  } catch (error) {
    console.error('PDF Generation Error:', error);
    return NextResponse.json({ error: 'Failed to generate PDF' }, { status: 500 });
  }
}

/** Standard PDF fonts only cover WinAnsi; anything else (emoji, CJK…) would throw. */
function safe(s: string): string {
  return s.replace(/[^\u0020-\u007e\u00a0-\u00ff\u2013\u2014\u2018\u2019\u201c\u201d\u2022\u2026\u20ac]/g, '?');
}

function wrap(s: string, f: PDFFont, size: number, maxWidth: number): string[] {
  const words = s.split(/\s+/);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    const next = cur ? `${cur} ${w}` : w;
    if (f.widthOfTextAtSize(next, size) > maxWidth && cur) {
      lines.push(cur);
      cur = w;
    } else {
      cur = next;
    }
  }
  if (cur) lines.push(cur);
  return lines;
}

function clip(s: string, f: PDFFont, size: number, maxWidth: number): string {
  if (f.widthOfTextAtSize(s, size) <= maxWidth) return s;
  let out = s;
  while (out.length > 1 && f.widthOfTextAtSize(`${out}…`, size) > maxWidth) out = out.slice(0, -1);
  return `${out}…`;
}
