#!/usr/bin/env node
/**
 * Concatenate migrations into one script you can paste into the Supabase SQL
 * editor.
 *
 * Why this exists: `supabase db push` only applies what the *remote* migration
 * history table says is missing. On a project that was never pushed from this
 * checkout, that history can be empty, and the push then tries to replay the
 * original schema and dies on "relation profiles already exists" — leaving
 * nothing applied. Running the SQL directly sidesteps the history entirely,
 * which is the safer path for a one-time catch-up.
 *
 * Usage
 *   node scripts/db/pending-sql.mjs                     # everything from 20260919 on
 *   node scripts/db/pending-sql.mjs --since 20260920000000
 *   npm run db:sql                 # writes ./catchup.sql
 *   npm run db:sql -- --out /tmp/x.sql
 *
 * It writes a file rather than printing, because `npm run db:sql > catchup.sql`
 * also captures npm's own "> velocewealth@0.1.0 db:sql" banner, and the SQL
 * editor then fails on the first line. Use --stdout if you want to pipe it.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const args = process.argv.slice(2);
const sinceIdx = args.indexOf('--since');
const since = sinceIdx >= 0 ? args[sinceIdx + 1] : '20260919000000';
const outIdx = args.indexOf('--out');
const outPath = outIdx >= 0 ? args[outIdx + 1] : 'catchup.sql';
const toStdout = args.includes('--stdout');

const dir = 'supabase/migrations';
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.sql') && f.slice(0, 14) >= since)
  .sort();

if (files.length === 0) {
  console.error(`No migration at or after ${since}.`);
  process.exit(1);
}

const out = [
  '-- Velocewealth · catch-up migration script',
  `-- ${files.length} migration(s) from ${files[0]} onwards, in order.`,
  '-- Generated by scripts/db/pending-sql.mjs — do not edit by hand.',
  '--',
  '-- Paste this whole file into the Supabase SQL editor and run it once. Every',
  '-- statement is guarded (if not exists / drop ... if exists), so a re-run is',
  '-- harmless and a partial failure can be retried.',
  '--',
  '-- Deliberately NOT wrapped in a transaction: ALTER TYPE ... ADD VALUE is',
  '-- happiest outside one, and if a statement fails you want the earlier ones',
  '-- kept rather than rolled back, then to re-run the whole file.',
  '--',
  '-- Afterwards, tell the CLI these are applied so a future `db push` does not',
  '-- try to replay them:',
  ...files.map((f) => `--   npx supabase@latest migration repair --status applied ${f.slice(0, 14)}`),
  '',
];

for (const f of files) {
  out.push(`-- ${'='.repeat(68)}`, `-- ${f}`, `-- ${'='.repeat(68)}`, '');
  out.push(readFileSync(join(dir, f), 'utf8').trimEnd(), '');
}

const sql = out.join('\n');
if (toStdout) {
  process.stdout.write(sql);
  console.error(`${files.length} migrations → stdout`);
} else {
  writeFileSync(outPath, sql);
  console.log(`${files.length} migrations → ${outPath} (${sql.split('\n').length} lines)`);
  console.log('Paste the whole file into the Supabase SQL editor and run it once.');
}
